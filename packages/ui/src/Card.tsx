import { forwardRef, type HTMLAttributes } from "react";
import { cn } from "./cn";

export const Card = forwardRef<HTMLDivElement, HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "rounded-lg bg-surface-container-lowest border border-outline-variant/40 shadow-sm",
        className,
      )}
      {...props}
    />
  ),
);
Card.displayName = "Card";

